#!/usr/bin/env python3
"""Build the reviewed ArduPilot STATUSTEXT matcher and offline replay vectors."""
import argparse
import json
import re
import string
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CATALOG = ROOT / "localization/zh-Hans/ardupilot-status-catalog.json"
OUTPUT = ROOT / "ExtLibs/ArduPilot/Mavlink/ArduPilotStatusTextCatalog.Data.cs"
UI = ROOT / "localization/zh-Hans/code-translations.json"
FORMAT = re.compile(r"%([-+ #0]*)(\d*)(?:\.(\d+))?(h{1,2}|l{1,2})?([diufsc%])")
FIELDS = {
    "battery": ("[1-9]", "2"),
    "sysid": ("(?:25[0-5]|2[0-4][0-9]|1[0-9]{2}|[1-9][0-9]?|0)", "42"),
    "thruster": ("(?:1[0-6]|[1-9])", "4"),
    "mode": ("[A-Za-z][A-Za-z0-9_ /-]{0,22}", "ALT_HOLD"),
    "parameter": ("[A-Z][A-Z0-9_]{0,15}", "EK3_ENABLE"),
    "message_id": ("[A-Z][A-Z0-9_]{0,49}", "NAV_CONTROLLER_OUTPUT"),
}
FIRMWARE_TYPES = {"DEV": 0, "BETA": 128, "OFFICIAL": 255}


def csharp(value):
    return json.dumps(value, ensure_ascii=False)


def compile_format(text, overrides):
    """Keep format literals literal and capture only typed value fields."""
    pattern = []
    key = []
    example = []
    values = []
    offset = 0
    field = 0
    while (start := text.find("%", offset)) >= 0:
        literal = text[offset:start]
        pattern.append(re.escape(literal))
        key.append(literal)
        example.append(literal)
        token = FORMAT.match(text, start)
        if not token:
            raise ValueError(f"Unsupported printf field in {text!r}")
        flags, width, precision, _, kind = token.groups()
        offset = token.end()
        if kind == "%":
            pattern.append("%")
            key.append("%")
            example.append("%")
            continue

        override = overrides[field] if field < len(overrides) else None
        field += 1
        if isinstance(override, str) and override.startswith("=") and kind in "sc":
            fixed = override[1:]
            pattern.append(re.escape(fixed))
            key.append(fixed)
            example.append(fixed)
            continue
        if override in FIELDS:
            grammar, sample = FIELDS[override]
        elif override:
            raise ValueError(f"Unknown field override {override!r}")
        elif kind in "diu":
            grammar = ("-?" if kind != "u" else "") + "[0-9]{1,10}"
            sample = "3" if kind == "u" else "17"
        elif kind == "f":
            decimals = 6 if precision is None else int(precision)
            if decimals > 9:
                raise ValueError(f"Unsupported decimal precision in {text!r}")
            grammar = "-?[0-9]{1,12}" + (rf"\.[0-9]{{{decimals}}}" if decimals else "")
            sample = "-3" + (f".{('25' * 5)[:decimals]}" if decimals else "")
        else:
            raise ValueError(f"Unbounded printf field in {text!r}; choose a reviewed field type or literal")
        if width and "0" not in flags:
            if int(width) > 12:
                raise ValueError(f"Unsupported width in {text!r}")
            grammar = rf" {{0,{max(0, int(width) - 1)}}}" + grammar
        pattern.append("(" + grammar + ")")
        key.append("{" + str(len(values)) + "}")
        values.append(sample)
        example.append(sample)
    literal = text[offset:]
    pattern.append(re.escape(literal))
    key.append(literal)
    example.append(literal)
    if len(overrides) > field:
        raise ValueError(f"Unused field override in {text!r}")
    return "".join(pattern), "".join(key), "".join(example), values


def build(catalog, translations):
    lines = [
        "// Generated by scripts/localization/build_ardupilot_status_catalog.py.",
        "using System.Collections.Generic;",
        "",
        "namespace MissionPlanner",
        "{",
        "    internal static partial class ArduPilotStatusTextCatalog",
        "    {",
        "        private static Dictionary<(Family, uint, string), int> CreateBuildIndex() =>",
        "            new Dictionary<(Family, uint, string), int>",
        "            {",
    ]
    for index, info in enumerate(catalog["builds"]):
        family, version, kind, commit, tag = info
        major, minor, patch = (int(v) for v in version.split("."))
        lines.append(f'                [(Family.{family}, 0x{major:02x}{minor:02x}{patch:02x}{FIRMWARE_TYPES[kind]:02x}u, '
                     f'"{commit[:8]}")] = {index}, // {tag}')
    lines.extend(["            };", "", "        private static StatusRule[][] CreateRules()", "        {"])
    for index, indices in enumerate(catalog["build_sets"]):
        if indices != sorted(set(indices)) or not indices or indices[-1] >= len(catalog["builds"]):
            raise ValueError(f"Invalid set of firmware builds at {index}")
        values = ", ".join(str(i) for i in indices)
        lines.append(f"            var builds{index} = new[] {{ {values} }};")
    lines.extend(["            return new[]", "            {"])
    fixtures = []
    for severity in range(8):
        rules = [r for r in catalog["rules"] if r["severity"] == severity]
        if not rules:
            lines.append("                System.Array.Empty<StatusRule>(),")
            continue
        lines.extend(["                new[]", "                {"])
        for rule in rules:
            pattern, key, sample, args = compile_format(rule["format"], rule.get("fields", []))
            if key not in translations:
                raise ValueError(f"Missing localized resource for {key!r}")
            translated = translations[key]
            fields = {field for _, field, spec, conv in string.Formatter().parse(translated) if field is not None}
            if fields != {str(i) for i in range(len(args))}:
                raise ValueError(f"Translation does not retain exactly the fields in {key!r}")
            lines.append(f"                    new StatusRule({csharp(pattern)}, {csharp(key)}, builds{rule['build_set']}),")
            fixtures.append([severity, sample, translated.format(*args), catalog["build_sets"][rule["build_set"]]])
        lines.extend(["                },"])
    lines.extend(["            };", "        }", "    }", "}", ""])
    return "\n".join(lines), fixtures


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--fixtures", type=Path)
    args = parser.parse_args()
    catalog = json.loads(CATALOG.read_text(encoding="utf-8"))
    translations = json.loads(UI.read_text(encoding="utf-8"))
    source, fixtures = build(catalog, translations)
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != source:
            raise SystemExit("ArduPilot STATUSTEXT matcher needs regeneration")
    else:
        OUTPUT.write_text(source, encoding="utf-8")
    if args.fixtures:
        args.fixtures.write_text(json.dumps({"builds": catalog["builds"], "cases": fixtures},
                                           ensure_ascii=False, separators=(",", ":")) + "\n", encoding="utf-8")
    print(f"ArduPilot STATUSTEXT: {len(catalog['builds'])} builds, {len(fixtures)} rules, "
          f"{sum(len(f[3]) for f in fixtures)} build-specific replay vectors")


if __name__ == "__main__":
    main()
